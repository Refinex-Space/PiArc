export type Pose = keyof typeof POSES;

/** A pose as one SVG path in block units: each row's runs as rectangles, standing on the floor. */
export function posePath(pose: Pose, left: number): string {
  const rows = POSES[pose];
  const top = STAGE_ROWS - rows.length;
  let d = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') {
        x += 1;
        continue;
      }
      let end = x;
      while (row[end] === '#') end += 1;
      d += `M${String(left + x)} ${String(top + y)}h${String(end - x)}v1h${String(x - end)}z`;
      x = end;
    }
  });
  return d;
}
