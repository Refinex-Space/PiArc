// Builds the Core native module (crates/piarc-napi) with @napi-rs/cli (`npm run build:core`).
//
//   node scripts/dev/build-core.mjs [--flavor development|release|all] [--target <triple>]
//
// - `development` (default) enables the `testing` cargo feature: demo event sources, echo,
//   event counters and panic triggers. Tests, L4 and benchmarks load this build.
// - `release` leaves it off; release packages ship it.
// - Output: target/piarc-core/<flavor>/piarc-core.<platform>-<arch>[-msvc].node, always in
//   the cargo release profile.
// - The TypeScript declarations NAPI-RS generates are formatted with Prettier and written to
//   apps/desktop/src/main/core/native/ (piarc-core.d.ts for release, piarc-core.testing.d.ts
//   for development). They are the L1 snapshot that scripts/ci/check-core-types.mjs checks.
// - `--target` cross-builds one of the four shipping targets (the Rust target must be
//   installed); without it the host target is built.
// - Windows targets: the DLLs the module imports (`CORE_WINDOWS_DLLS`, libghostty-vt) are
//   copied next to it from the artefact crates/piarc-ghostty-sys/build.rs verified.
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { parseArgs } from 'node:util';

import { NapiCli } from '@napi-rs/cli';
import * as prettier from 'prettier';

import {
  CORE_BINARY_STEM,
  CORE_TARGETS,
  CORE_WINDOWS_DLLS,
  coreBuildDir,
} from '../../apps/desktop/core-binary.mjs';
import { parseBuildFlavor } from '../../apps/desktop/fuses.mjs';
import { ghosttyArtifact, hostTarget } from '../lib/ghostty-vt.mjs';
import { isMain, repoRoot } from '../lib/repo.mjs';

/** @typedef {import('../../apps/desktop/fuses.mjs').BuildFlavor} BuildFlavor */

/** Committed declaration snapshots, relative to the repository root. */
export const DECLARATIONS_DIR = path.join('apps', 'desktop', 'src', 'main', 'core', 'native');

/** @type {Readonly<Record<BuildFlavor, string>>} */
export const DECLARATION_FILES = Object.freeze({
  release: `${CORE_BINARY_STEM}.d.ts`,
  development: `${CORE_BINARY_STEM}.testing.d.ts`,
});

const HEADER = '// Generated by `npm run build:core` from crates/piarc-napi. Do not edit.\n';

/**
 * Builds one flavor and writes its formatted declarations to `declarationsDir`.
 * @param {{ flavor: BuildFlavor, target?: string | undefined, declarationsDir?: string }} options
 * @returns {Promise<{ binary: string, declarations: string }>}
 */
export async function buildCore({ flavor, target, declarationsDir }) {
  if (target !== undefined && !(target in CORE_TARGETS)) {
    throw new Error(
      `Unknown target ${target}; expected one of ${Object.keys(CORE_TARGETS).join(', ')}`,
    );
  }
  const outputDir = coreBuildDir(repoRoot, flavor);
  await mkdir(outputDir, { recursive: true });
  const rawDeclarations = `${CORE_BINARY_STEM}.raw.d.ts`;
  const { task } = await new NapiCli().build({
    cwd: repoRoot,
    manifestPath: path.join('crates', 'piarc-napi', 'Cargo.toml'),
    package: 'piarc-napi',
    packageJsonPath: 'package.json',
    configPath: path.join('crates', 'piarc-napi', 'napi.json'),
    outputDir,
    platform: true,
    noJsBinding: true,
    dts: rawDeclarations,
    dtsHeader: HEADER,
    release: true,
    // String enums become type-only unions: the main process compares plain strings.
    constEnum: false,
    ...(target === undefined ? {} : { target }),
    ...(flavor === 'development' ? { features: ['testing'] } : {}),
    cargoOptions: ['--locked'],
  });
  const outputs = await task;
  const binary = outputs.find((output) => output.path.endsWith('.node'))?.path;
  if (binary === undefined) {
    throw new Error('@napi-rs/cli produced no .node file');
  }
  await copyWindowsDlls(target, outputDir);
  const raw = await readFile(path.join(outputDir, rawDeclarations), 'utf8');
  // Format as the committed file would be, wherever this copy goes (the drift check writes
  // to a temporary directory, outside the reach of the repository's Prettier config).
  const committed = path.join(repoRoot, DECLARATIONS_DIR, DECLARATION_FILES[flavor]);
  const declarations = path.join(
    declarationsDir ?? path.dirname(committed),
    DECLARATION_FILES[flavor],
  );
  const config = (await prettier.resolveConfig(committed)) ?? {};
  await mkdir(path.dirname(declarations), { recursive: true });
  await writeFile(
    declarations,
    await prettier.format(raw, { ...config, filepath: committed }),
    'utf8',
  );
  return { binary, declarations };
}

/**
 * Copies `CORE_WINDOWS_DLLS` next to the module when it is built for Windows.
 * @param {string | undefined} target `--target`, or undefined for the host
 * @param {string} outputDir
 */
async function copyWindowsDlls(target, outputDir) {
  const triple = target ?? (await hostTarget());
  if (CORE_TARGETS[triple]?.platform !== 'win32') {
    return;
  }
  // Same profile and target as the module, so cargo reuses the verified unpacked artefact.
  const { dll } = await ghosttyArtifact({ target, release: true });
  if (dll === undefined || !CORE_WINDOWS_DLLS.includes(path.basename(dll))) {
    throw new Error(`the libghostty-vt artefact for ${triple} names no DLL from CORE_WINDOWS_DLLS`);
  }
  await copyFile(dll, path.join(outputDir, path.basename(dll)));
}

async function main() {
  const { values } = parseArgs({
    options: { flavor: { type: 'string' }, target: { type: 'string' } },
  });
  /** @type {BuildFlavor[]} */
  const flavors =
    values.flavor === 'all'
      ? ['development', 'release']
      : [parseBuildFlavor(values.flavor ?? 'development')];
  for (const flavor of flavors) {
    const { binary, declarations } = await buildCore({ flavor, target: values.target });
    console.log(`built ${path.relative(repoRoot, binary)} (${flavor})`);
    console.log(`wrote ${path.relative(repoRoot, declarations)}`);
  }
}

if (isMain(import.meta.url)) {
  await main();
}
