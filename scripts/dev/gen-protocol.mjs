// Generates the protocol schema and TypeScript types (`npm run gen:protocol`).
//
// 1. Runs the piarc-protocol `export-schema` binary, which prints every schema file.
// 2. Writes them to packages/protocol/schema/.
// 3. Generates packages/protocol/src/generated/ from the schema with
//    json-schema-to-typescript.
// 4. Formats everything with the repository's Prettier configuration, so the generated
//    files pass `prettier --check` and the drift check compares formatted output.
//
// The generator owns both output directories: files it no longer produces are removed.
// `--out <dir>` writes into another root (used by check-protocol-drift.mjs).
import { mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { parseArgs } from 'node:util';
import { compile } from 'json-schema-to-typescript';
import * as prettier from 'prettier';
import { capture, isMain, isRecord, repoRoot } from '../lib/repo.mjs';

/** Output directories, relative to the root. */
export const SCHEMA_DIR = path.join('packages', 'protocol', 'schema');
export const GENERATED_DIR = path.join('packages', 'protocol', 'src', 'generated');

const SCHEMA_FILE = 'ahp.schema.json';
const CONTRACTS_FILE = 'contracts.json';
const BANNER = '// Generated by `npm run gen:protocol` from the piarc-protocol crate. Do not edit.';

/** Keywords that give a schema node a type; a node without any of them accepts any value. */
const TYPE_KEYWORDS = [
  'type',
  '$ref',
  'anyOf',
  'oneOf',
  'allOf',
  'const',
  'enum',
  'properties',
  'items',
  'tsType',
];

/**
 * Runs the Rust exporter and returns its files, keyed by file name.
 * @returns {Promise<Record<string, unknown>>}
 */
async function exportSchema() {
  const stdout = await capture('cargo', [
    'run',
    '--quiet',
    '--locked',
    '-p',
    'piarc-protocol',
    '--bin',
    'export-schema',
  ]);
  /** @type {unknown} */
  const files = JSON.parse(stdout);
  if (!isRecord(files)) {
    throw new Error('export-schema did not print a JSON object');
  }
  return files;
}

/**
 * Adapts a schema node for json-schema-to-typescript without changing what it accepts:
 * - `$ref` with sibling keywords (descriptions) becomes `allOf: [{ $ref }]`, otherwise the
 *   generator inlines a renamed copy of the referenced type;
 * - a node with no type keyword (any JSON value) becomes `unknown` instead of an object.
 * Exported for tests.
 * @param {unknown} node
 * @returns {unknown}
 */
export function prepareForTypeScript(node) {
  if (Array.isArray(node)) {
    return node.map(prepareForTypeScript);
  }
  if (!isRecord(node)) {
    return node;
  }
  /** @type {Record<string, unknown>} */
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if ((key === 'properties' || key === '$defs') && isRecord(value)) {
      out[key] = Object.fromEntries(
        Object.entries(value).map(([name, schema]) => [name, prepareForTypeScript(schema)]),
      );
    } else {
      out[key] = prepareForTypeScript(value);
    }
  }
  const { $ref: ref, ...rest } = out;
  if (ref !== undefined && Object.keys(rest).length > 0) {
    return { ...rest, allOf: [{ $ref: ref }] };
  }
  if (!TYPE_KEYWORDS.some((keyword) => keyword in out)) {
    out.tsType = 'unknown';
  } else if (
    out.type === 'object' &&
    Object.keys(out).every((key) => ['type', 'description', 'title'].includes(key))
  ) {
    // Acknowledgements are objects with no declared members. An empty TS interface
    // would also accept numbers and strings.
    out.tsType = 'Record<string, never>';
  }
  return out;
}

/**
 * @param {Record<string, unknown>} contracts
 */
function protocolVersionOf(contracts) {
  const version = contracts.protocolVersion;
  if (typeof version !== 'string') {
    throw new Error(`${CONTRACTS_FILE} has no protocolVersion string`);
  }
  return version;
}

/**
 * Produces every generated file, unformatted, keyed by path relative to the root.
 * @returns {Promise<Map<string, string>>}
 */
async function buildFiles() {
  const exported = await exportSchema();
  const schema = exported[SCHEMA_FILE];
  const contracts = exported[CONTRACTS_FILE];
  if (!isRecord(schema) || !isRecord(contracts)) {
    throw new Error(`export-schema must print ${SCHEMA_FILE} and ${CONTRACTS_FILE}`);
  }
  /** @type {Map<string, string>} */
  const files = new Map();
  for (const [name, value] of Object.entries(exported)) {
    files.set(path.join(SCHEMA_DIR, name), `${JSON.stringify(value, null, 2)}\n`);
  }

  const prepared = prepareForTypeScript(schema);
  if (!isRecord(prepared)) {
    throw new Error('prepared schema is not an object');
  }
  // Core API payloads share definitions with AHP without becoming AHP messages.
  const { $defs, ...ahp } = prepared;
  if (!isRecord($defs)) {
    throw new Error('prepared schema has no definitions');
  }
  const surface = {
    title: 'ProtocolValue',
    anyOf: ['AhpMessage', 'ApprovalRequest', 'ApprovalAnswer', 'AnswerStatus'].map((name) => ({
      $ref: `#/$defs/${name}`,
    })),
    $defs: { ...$defs, AhpMessage: ahp },
  };
  const types = await compile(surface, 'ProtocolValue', {
    additionalProperties: false,
    unreachableDefinitions: true,
    bannerComment: BANNER,
    format: false,
  });
  files.set(path.join(GENERATED_DIR, 'ahp.ts'), types);
  files.set(
    path.join(GENERATED_DIR, 'version.ts'),
    [
      BANNER,
      '',
      '/** AHP version spoken by this build (`major.minor`), defined in piarc-protocol. */',
      `export const PROTOCOL_VERSION = ${JSON.stringify(protocolVersionOf(contracts))};`,
      '',
    ].join('\n'),
  );
  return files;
}

/**
 * Removes every file in `dir` and recreates it empty.
 * @param {string} dir
 */
async function resetDir(dir) {
  await rm(dir, { recursive: true, force: true });
  await mkdir(dir, { recursive: true });
}

/**
 * Generates and writes all files under `outRoot` (default: the repository).
 * Prettier options are resolved for the file's location in the repository, so output
 * written elsewhere is formatted identically.
 * @param {string} [outRoot]
 * @returns {Promise<string[]>} written paths, relative to `outRoot`
 */
export async function generateProtocol(outRoot = repoRoot) {
  const files = await buildFiles();
  await resetDir(path.join(outRoot, SCHEMA_DIR));
  await resetDir(path.join(outRoot, GENERATED_DIR));
  const written = [];
  for (const [relative, content] of files) {
    const repoPath = path.join(repoRoot, relative);
    const config = (await prettier.resolveConfig(repoPath)) ?? {};
    const formatted = await prettier.format(content, { ...config, filepath: repoPath });
    await writeFile(path.join(outRoot, relative), formatted, 'utf8');
    written.push(relative);
  }
  return written.sort();
}

/**
 * Lists the files currently in the output directories under `root`, relative to `root`.
 * @param {string} root
 * @returns {Promise<string[]>}
 */
export async function listGenerated(root) {
  const listed = [];
  for (const dir of [SCHEMA_DIR, GENERATED_DIR]) {
    /** @type {string[]} */
    let names = [];
    try {
      names = await readdir(path.join(root, dir));
    } catch (error) {
      // A missing directory simply has no files; the drift check reports them as missing.
      if (!(error instanceof Error && 'code' in error && error.code === 'ENOENT')) {
        throw error;
      }
    }
    listed.push(...names.map((name) => path.join(dir, name)));
  }
  return listed.sort();
}

async function main() {
  const { values } = parseArgs({ options: { out: { type: 'string' } } });
  const outRoot = values.out === undefined ? repoRoot : path.resolve(values.out);
  const written = await generateProtocol(outRoot);
  for (const file of written) {
    console.log(`wrote ${file}`);
  }
}

if (isMain(import.meta.url)) {
  await main();
}
