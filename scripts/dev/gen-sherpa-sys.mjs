// Generates crates/piarc-sherpa-sys/src from the published sherpa-onnx-sys crate (ADR-0094).
//
//   node scripts/dev/gen-sherpa-sys.mjs [--check]
//
// The upstream crate declares the C API as `extern "C"` functions that the linker resolves at
// build time. PiArc loads the C API library at run time instead, so every declaration becomes a
// `pub unsafe fn` of the same name and signature that calls through the function table that
// `loader.rs` resolves with libloading; a function whose library or symbol is missing returns a
// null pointer or zero. Struct definitions, constants and module layout are copied unchanged, so
// the upstream safe wrapper (`sherpa-onnx`) builds against this crate through
// `[patch.crates-io]`.
//
// The crate archive is downloaded from static.crates.io and checked against the crates.io
// checksum below; `--check` regenerates into memory and fails when the committed files differ.
import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import { mkdir, mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { parseArgs } from 'node:util';

import { isMain, repoRoot, run } from '../lib/repo.mjs';

export const UPSTREAM = {
  name: 'sherpa-onnx-sys',
  version: '2.0.1',
  // crates.io index checksum of sherpa-onnx-sys 2.0.1 (the .crate file's SHA-256).
  sha256: '5bc46e5fb3aab39141d48ad8763d0891e0b9e0fbc8e3bdefaa63704d1bf00054',
};
const CRATE_DIR = path.join(repoRoot, 'crates', 'piarc-sherpa-sys');
const CACHE = path.join(repoRoot, '.tools', 'cache', 'crates');

/** Header of every generated file. */
const HEADER = [
  `// Generated by scripts/dev/gen-sherpa-sys.mjs from ${UPSTREAM.name} ${UPSTREAM.version}`,
  '// (Apache-2.0, https://github.com/k2-fsa/sherpa-onnx). Do not edit: change the generator and',
  '// run it again. The extern declarations were turned into run-time calls (see loader.rs).',
  '',
].join('\n');

/**
 * @typedef {{ name: string, params: Array<{ name: string, type: string }>, ret: string }} Decl
 */

/**
 * Splits `text` at top-level commas (outside (), <> and []).
 * @param {string} text
 * @returns {string[]}
 */
export function splitTopLevel(text) {
  /** @type {string[]} */
  const parts = [];
  let depth = 0;
  let current = '';
  for (const char of text) {
    if ('(<['.includes(char)) depth += 1;
    if (')>]'.includes(char)) depth -= 1;
    if (char === ',' && depth === 0) {
      parts.push(current);
      current = '';
    } else {
      current += char;
    }
  }
  parts.push(current);
  return parts.map((part) => part.trim()).filter((part) => part !== '');
}

/**
 * Removes `//` comments (the declarations carry no strings with slashes).
 * @param {string} text
 */
function stripComments(text) {
  return text.replace(/\/\/[^\n]*/g, '');
}

/**
 * Parses the body of an `extern "C" { … }` block into declarations.
 * @param {string} body
 * @returns {Decl[]}
 */
export function parseExternBlock(body) {
  /** @type {Decl[]} */
  const decls = [];
  for (const item of stripComments(body).split(';')) {
    const text = item.replace(/\s+/g, ' ').trim();
    if (text === '') continue;
    const match = /^pub fn (\w+)\s*\((.*)\)\s*(?:->\s*(.+))?$/.exec(text);
    if (match === null) throw new Error(`unrecognised extern item: ${text}`);
    const [, name = '', params = '', ret = ''] = match;
    decls.push({
      name,
      params: splitTopLevel(params).map((param) => {
        const colon = param.indexOf(':');
        if (colon < 0) throw new Error(`parameter without a type in ${name}: ${param}`);
        return { name: param.slice(0, colon).trim(), type: param.slice(colon + 1).trim() };
      }),
      ret: ret.trim(),
    });
  }
  return decls;
}

/**
 * The value a wrapper returns when its function is not loaded.
 * @param {string} ret
 */
function fallback(ret) {
  if (ret === '') return '()';
  if (ret.startsWith('*const')) return 'core::ptr::null()';
  if (ret.startsWith('*mut')) return 'core::ptr::null_mut()';
  if (/^(i8|i16|i32|i64|u8|u16|u32|u64|f32|f64|c_int|c_float|usize|isize)$/.test(ret)) {
    return 'Default::default()';
  }
  throw new Error(`no fallback for return type ${ret}`);
}

/**
 * The wrapper function of one declaration.
 * @param {Decl} decl
 */
function wrapper(decl) {
  const params = decl.params.map((p) => `${p.name}: ${p.type}`).join(', ');
  const args = decl.params.map((p) => p.name).join(', ');
  const ret = decl.ret === '' ? '' : ` -> ${decl.ret}`;
  return [
    `/// Calls \`${decl.name}\` of the loaded C API; without it returns a null pointer or zero.`,
    '///',
    '/// # Safety',
    '///',
    `/// Same contract as the C function \`${decl.name}\`: pointers must be valid for it.`,
    `pub unsafe fn ${decl.name}(${params})${ret} {`,
    `    match crate::loader::table().and_then(|table| table.${decl.name}) {`,
    `        // SAFETY: the symbol was resolved from the C API library with this exact signature`,
    `        // (generated from the same declaration); the caller upholds the C contract.`,
    `        Some(function) => unsafe { function(${args}) },`,
    `        None => ${fallback(decl.ret)},`,
    '    }',
    '}',
  ].join('\n');
}

/**
 * Rewrites one upstream source file: every `extern "C"` block becomes wrappers.
 * @param {string} source
 * @returns {{ text: string, decls: Decl[] }}
 */
export function rewriteSource(source) {
  /** @type {Decl[]} */
  const all = [];
  let text = '';
  let rest = source;
  for (;;) {
    const start = rest.indexOf('extern "C" {');
    if (start < 0) {
      text += rest;
      break;
    }
    let depth = 0;
    let end = -1;
    for (let i = start + 'extern "C" '.length; i < rest.length; i += 1) {
      if (rest[i] === '{') depth += 1;
      if (rest[i] === '}') {
        depth -= 1;
        if (depth === 0) {
          end = i;
          break;
        }
      }
    }
    if (end < 0) throw new Error('unterminated extern block');
    const decls = parseExternBlock(rest.slice(start + 'extern "C" {'.length, end));
    all.push(...decls);
    text += rest.slice(0, start) + decls.map(wrapper).join('\n\n');
    rest = rest.slice(end + 1);
  }
  return { text, decls: all };
}

/**
 * The function table: one optional function pointer per declaration, resolved by name.
 * @param {Array<{ module: string, decls: Decl[] }>} modules
 */
function tableSource(modules) {
  const fields = [];
  const resolves = [];
  const checks = [];
  for (const { decls } of modules) {
    for (const decl of decls) {
      const params = decl.params.map((p) => qualify(p.type)).join(', ');
      const ret = decl.ret === '' ? '' : ` -> ${qualify(decl.ret)}`;
      fields.push(`    pub(crate) ${decl.name}: Option<unsafe extern "C" fn(${params})${ret}>,`);
      resolves.push(`            ${decl.name}: symbol(library, b"${decl.name}\\0"),`);
      checks.push(`            "${decl.name}" => self.${decl.name}.is_some(),`);
    }
  }
  return [
    HEADER,
    '//! The C API as a table of function pointers, resolved once when the library is loaded.',
    '',
    'use std::os::raw::{c_char, c_float, c_int, c_void};',
    '',
    '/// One optional function pointer per C API function (`None` when the library lacks it).',
    '#[expect(non_snake_case, reason = "fields carry the C function names")]',
    'pub(crate) struct Table {',
    ...fields,
    '}',
    '',
    'impl Table {',
    '    /// Resolves every function of `library`; missing ones stay `None`.',
    '    #[expect(clippy::too_many_lines, reason = "one line per generated C function")]',
    '    pub(crate) fn resolve(library: &libloading::Library) -> Self {',
    '        Self {',
    ...resolves,
    '        }',
    '    }',
    '',
    '    /// Whether the function `name` was found in the library.',
    '    #[expect(clippy::too_many_lines, reason = "one line per generated C function")]',
    '    pub(crate) fn has(&self, name: &str) -> bool {',
    '        match name {',
    ...checks,
    '            _ => false,',
    '        }',
    '    }',
    '}',
    '',
    '/// Resolves one symbol as a function pointer of type `F`, or `None`.',
    'fn symbol<F: Copy>(library: &libloading::Library, name: &[u8]) -> Option<F> {',
    '    // SAFETY: `F` is the generated signature of the C function `name` (same declaration as',
    '    // the upstream bindings); the pointer stays valid while the library is loaded, which is',
    '    // for the rest of the process (the loader never unloads it).',
    '    unsafe { library.get::<F>(name).ok().map(|symbol| *symbol) }',
    '}',
    '',
    '// Silence unused-import warnings for types only some signatures use.',
    'const _: Option<(*const c_char, c_float, c_int, *const c_void)> = None;',
    '',
  ].join('\n');
}

/**
 * Qualifies the bare type names of a declaration so the table (in its own module) can name
 * them: the crate root re-exports every module (`pub use module::*`), so `Foo` becomes
 * `crate::Foo`; `super::m::Foo` becomes `crate::m::Foo`; primitives stay.
 * @param {string} type
 */
function qualify(type) {
  return type
    .replace(/\bsuper::/g, 'crate::')
    .replace(/(?<![:\w])([A-Z]\w*)/g, (name) => (name === 'Option' ? name : `crate::${name}`));
}

/**
 * Downloads (or reuses) the upstream crate archive and checks its checksum.
 * @returns {Promise<string>} path of the extracted crate
 */
async function upstreamCrate() {
  const file = path.join(CACHE, `${UPSTREAM.name}-${UPSTREAM.version}.crate`);
  if (!existsSync(file)) {
    await mkdir(CACHE, { recursive: true });
    const url = `https://static.crates.io/crates/${UPSTREAM.name}/${UPSTREAM.name}-${UPSTREAM.version}.crate`;
    const response = await fetch(url);
    if (!response.ok) throw new Error(`downloading ${url} failed: HTTP ${String(response.status)}`);
    await writeFile(file, new Uint8Array(await response.arrayBuffer()));
  }
  const digest = createHash('sha256')
    .update(await readFile(file))
    .digest('hex');
  if (digest !== UPSTREAM.sha256) {
    await rm(file);
    throw new Error(`${file} has SHA-256 ${digest}, expected ${UPSTREAM.sha256}`);
  }
  const into = await mkdtemp(path.join(tmpdir(), 'piarc-sherpa-sys-'));
  const code = await run('tar', ['-xzf', file, '-C', into]);
  if (code !== 0) throw new Error(`tar could not extract ${file}`);
  return path.join(into, `${UPSTREAM.name}-${UPSTREAM.version}`);
}

/**
 * Generates the source files.
 * @returns {Promise<Map<string, string>>} relative path under src/ → content
 */
export async function generate() {
  const crate = await upstreamCrate();
  try {
    /** @type {Map<string, string>} */
    const files = new Map();
    /** @type {Array<{ module: string, decls: Decl[] }>} */
    const modules = [];
    const sources = (await readdir(path.join(crate, 'src'))).filter((f) => f.endsWith('.rs')).sort();
    for (const name of sources) {
      const source = await readFile(path.join(crate, 'src', name), 'utf8');
      const { text, decls } = rewriteSource(source);
      const module = name.slice(0, -'.rs'.length);
      modules.push({ module, decls });
      if (name === 'lib.rs') {
        files.set(name, libSource(text));
      } else {
        // The crate root allows these lints with a reason; upstream repeats them per module.
        files.set(name, `${HEADER}${text.replace(/^#!\[allow\([^\]]*\)\]\n/gm, '')}`);
      }
    }
    files.set('table.rs', tableSource(modules));
    return files;
  } finally {
    await rm(path.dirname(crate), { recursive: true, force: true });
  }
}

/**
 * The crate root: upstream's root without its build-script documentation, plus the loader.
 * @param {string} text upstream lib.rs with the extern block already rewritten
 */
function libSource(text) {
  const body = text.replace(/^(\/\/![^\n]*\n)+\n?/, '');
  return [
    HEADER,
    '//! Run-time bindings to the sherpa-onnx C API (ADR-0094): the declarations of',
    `//! ${UPSTREAM.name} ${UPSTREAM.version}, called through the library that [\`load\`] opens`,
    '//! instead of being linked at build time. There is no build script and nothing is',
    '//! downloaded; `Resources/speech/runtime/` holds the verified libraries.',
    '//!',
    '//! Does not: decide when to load, verify the library files (piarc-speech does), or offer',
    '//! a safe API (the upstream `sherpa-onnx` crate does, built against this crate).',
    '//!',
    '//! Depends on: libloading only.',
    '',
    '#![allow(unsafe_code, reason = "a -sys crate: every function is an FFI call (ADR-0094)")]',
    '#![allow(non_snake_case, reason = "C function and field names, copied from upstream")]',
    '#![allow(non_camel_case_types, reason = "C type names, copied from upstream")]',
    '#![allow(non_upper_case_globals, reason = "C constant names, copied from upstream")]',
    '#![allow(clippy::all, reason = "definitions are copied unchanged from upstream")]',
    '',
    'mod loader;',
    'mod table;',
    '',
    'pub use loader::{LoadError, is_loaded, load, runtime_files};',
    '',
    body.replace(/#!\[allow\([^\]]*\)\]\n/g, ''),
  ].join('\n');
}

async function main() {
  const { values } = parseArgs({ options: { check: { type: 'boolean', default: false } } });
  const files = await generate();
  const src = path.join(CRATE_DIR, 'src');
  const stale = [];
  for (const [name, content] of files) {
    const target = path.join(src, name);
    if (values.check) {
      const current = existsSync(target) ? await readFile(target, 'utf8') : '';
      if (current !== content) stale.push(name);
    } else {
      await mkdir(src, { recursive: true });
      await writeFile(target, content);
    }
  }
  if (values.check && stale.length > 0) {
    console.error(`crates/piarc-sherpa-sys/src is out of date: ${stale.join(', ')}`);
    console.error('Run: node scripts/dev/gen-sherpa-sys.mjs');
    process.exitCode = 1;
    return;
  }
  console.log(values.check ? 'piarc-sherpa-sys is up to date' : `wrote ${String(files.size)} files`);
}

if (isMain(import.meta.url)) {
  await main();
}
