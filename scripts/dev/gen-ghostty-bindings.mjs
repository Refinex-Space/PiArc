// Regenerates crates/piarc-ghostty-sys/src/bindings.rs from the headers of the libghostty-vt
// artefact locked in crates/piarc-ghostty-sys/ghostty-vt.lock.json, with the pinned bindgen-cli
// in .tools/ (scripts/dev/install-tools.mjs) and the workspace rustfmt.
//
//   node scripts/dev/gen-ghostty-bindings.mjs           write the bindings
//   node scripts/dev/gen-ghostty-bindings.mjs --check   fail when the committed file differs
//
// Running it twice, or after a fresh checkout, must leave `git diff` empty (T10-A03). The
// headers are compiled as C23 so `GHOSTTY_ENUM_TYPED` makes every enum `int` on every target.
// bindgen loads libclang at run time (Xcode command line tools on macOS).
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { parseArgs } from 'node:util';

import { ghosttyArtifact } from '../lib/ghostty-vt.mjs';
import { isMain, repoRoot, run } from '../lib/repo.mjs';
import { localToolPath } from './install-tools.mjs';

export const BINDINGS_PATH = path.join(
  repoRoot,
  'crates',
  'piarc-ghostty-sys',
  'src',
  'bindings.rs',
);

/**
 * The bindgen command line that writes the bindings of `header` to `output`.
 * @param {{ header: string, include: string, version: string, output: string }} input
 * @returns {string[]}
 */
export function bindgenArgs({ header, include, version, output }) {
  return [
    header,
    '--output',
    output,
    '--rust-target',
    '1.85.0',
    '--rust-edition',
    '2024',
    '--allowlist-function',
    'ghostty_.*',
    '--allowlist-type',
    'Ghostty.*',
    '--allowlist-var',
    'GHOSTTY_.*',
    '--no-prepend-enum-name',
    '--no-doc-comments',
    '--merge-extern-blocks',
    '--formatter',
    'none',
    '--raw-line',
    `// Generated by scripts/dev/gen-ghostty-bindings.mjs from libghostty-vt ${version} (ghostty/vt.h). Do not edit.`,
    '--',
    '-I',
    include,
    '-std=c23',
  ];
}

/**
 * Generates the bindings into a temporary file and returns its formatted text.
 * @returns {Promise<string>}
 */
export async function generateBindings() {
  const artifact = await ghosttyArtifact();
  const dir = await mkdtemp(path.join(os.tmpdir(), 'piarc-bindgen-'));
  try {
    const output = path.join(dir, 'bindings.rs');
    const header = path.join(artifact.include, 'ghostty', 'vt.h');
    const bindgen = localToolPath('bindgen');
    const code = await run(
      bindgen,
      bindgenArgs({ header, include: artifact.include, version: artifact.version, output }),
    );
    if (code !== 0) {
      throw new Error(
        `bindgen failed with exit code ${String(code)} (install it with node scripts/dev/install-tools.mjs)`,
      );
    }
    const fmt = await run('rustfmt', [
      '--edition',
      '2024',
      '--config-path',
      path.join(repoRoot, 'rustfmt.toml'),
      output,
    ]);
    if (fmt !== 0) {
      throw new Error(`rustfmt failed with exit code ${String(fmt)}`);
    }
    return await readFile(output, 'utf8');
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}

async function main() {
  const { values } = parseArgs({ options: { check: { type: 'boolean' } } });
  const generated = await generateBindings();
  const relative = path.relative(repoRoot, BINDINGS_PATH);
  if (values.check === true) {
    const committed = await readFile(BINDINGS_PATH, 'utf8');
    if (committed !== generated) {
      console.error(
        `${relative} differs from the generated bindings; run this script to update it`,
      );
      process.exitCode = 1;
      return;
    }
    console.log(`${relative} matches the generated bindings`);
    return;
  }
  await writeFile(BINDINGS_PATH, generated, 'utf8');
  console.log(`wrote ${relative}`);
}

if (isMain(import.meta.url)) {
  await main();
}
