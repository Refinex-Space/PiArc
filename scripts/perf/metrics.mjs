/**
 * The budget of `metric` on `platform`.
 * @param {Metric} metric
 * @param {string} platform
 */
export function budgetOf(metric, platform) {
  if (typeof metric.budget === 'number') return metric.budget;
  return platform === 'win32' ? metric.budget.win32 : metric.budget.darwin;
}
