//! The credential vault: an encrypted file whose master key lives in the system credential
//! store.
//!
//! | Vault file | Master key | [`Vault::open`] |
//! |---|---|---|
//! | absent | absent | generates a key, stores it, writes an empty vault ([`OpenOutcome::Created`]) |
//! | absent | present | writes an empty vault under the existing key ([`OpenOutcome::Created`]) |
//! | present | present | authenticates and decrypts it ([`OpenOutcome::Opened`]) |
//! | present | absent | [`Error::MasterKeyMissing`]; no key is created, the file is not touched |
//! | any | store refuses, is locked or unavailable | [`Error::CredentialStore`] (retryable); nothing is written |
//! | modified, or unknown version | present | [`Error::Integrity`] or [`Error::UnsupportedVersion`]; nothing is returned |
//!
//! Every write seals the whole document under a new nonce and replaces the file atomically;
//! the in-memory state changes only after the new file is in place.

use std::path::{Path, PathBuf};
use std::sync::Arc;
use std::time::{SystemTime, UNIX_EPOCH};

use piarc_ports::{SecretName, SecretStore};
use serde_json::Value;

use crate::atomic::{self, RealSteps, WriteSteps};
use crate::document::{Document, StoredEntry, json_text};
use crate::error::{Error, Result};
use crate::format;
use crate::master_key::MasterKey;

/// Key prefixes the vault accepts: provider API keys, OAuth tokens, MCP tokens.
pub const KEY_PREFIXES: [&str; 3] = ["provider/", "oauth/", "mcp/"];
/// Longest accepted credential key, in bytes.
pub const MAX_KEY_BYTES: usize = 256;
/// Largest accepted credential value (its JSON text), in bytes.
pub const MAX_VALUE_BYTES: usize = 64 * 1024;

/// Where the vault and its master key live.
#[derive(Debug, Clone)]
pub struct VaultConfig {
    /// The vault file, normally `<data dir>/secrets.vault`.
    pub path: PathBuf,
    /// The master key item in the system credential store.
    pub master_key: SecretName,
}

/// How [`Vault::open`] found things.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum OpenOutcome {
    /// There was no vault file; an empty one was written. `new_key` tells whether a master key
    /// was generated and stored too.
    Created {
        /// Whether the master key was generated by this call.
        new_key: bool,
    },
    /// An existing vault was decrypted.
    Opened,
}

/// A read view of one stored credential.
#[derive(Debug, Clone, Copy)]
pub struct EntryView<'a> {
    /// The credential key, such as `provider/openai`.
    pub key: &'a str,
    /// The vault revision of the last write to this key.
    pub revision: u64,
    /// Unix milliseconds of the last write.
    pub updated_at: u64,
    /// The credential's JSON text.
    pub value: &'a str,
}

/// An open vault. Its plaintext and master key are zeroed when it is dropped.
pub struct Vault {
    path: PathBuf,
    key: MasterKey,
    document: Document,
    steps: Arc<dyn WriteSteps>,
}

impl std::fmt::Debug for Vault {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("Vault")
            .field("path", &self.path)
            .field("key", &self.key)
            .field("entries", &self.document.entries.len())
            .finish_non_exhaustive()
    }
}

impl Vault {
    /// Opens or creates the vault described by `config`; see the module table.
    ///
    /// # Errors
    ///
    /// See the module table; [`Error::Io`] when the file cannot be read or written.
    pub fn open(config: &VaultConfig, store: &dyn SecretStore) -> Result<(Self, OpenOutcome)> {
        Self::open_with(config, store, Arc::new(RealSteps))
    }

    pub(crate) fn open_with(
        config: &VaultConfig,
        store: &dyn SecretStore,
        steps: Arc<dyn WriteSteps>,
    ) -> Result<(Self, OpenOutcome)> {
        let path = config.path.clone();
        atomic::remove_leftovers(&path);
        let exists = path
            .try_exists()
            .map_err(|e| Error::io("cannot check", &path, e))?;
        // The store is consulted first: when it refuses, nothing is created.
        let key = MasterKey::load(store, &config.master_key)?;
        match (exists, key) {
            (true, None) => Err(Error::MasterKeyMissing { vault: path }),
            (true, Some(key)) => {
                let file = std::fs::read(&path).map_err(|e| Error::io("cannot read", &path, e))?;
                let plaintext = format::open(&key, &file)?;
                let document = Document::from_bytes(&plaintext).map_err(|_| Error::Integrity {
                    reason: "the decrypted vault is not a valid document",
                    key_id_matches: Some(true),
                })?;
                let vault = Self {
                    path,
                    key,
                    document,
                    steps,
                };
                Ok((vault, OpenOutcome::Opened))
            }
            (false, key) => {
                let new_key = key.is_none();
                let key = match key {
                    Some(key) => key,
                    None => {
                        let key = MasterKey::generate()?;
                        key.save(store, &config.master_key)?;
                        key
                    }
                };
                let vault = Self {
                    path,
                    key,
                    document: Document::default(),
                    steps,
                };
                vault.persist()?;
                Ok((vault, OpenOutcome::Created { new_key }))
            }
        }
    }

    /// The vault file.
    #[must_use]
    pub fn path(&self) -> &Path {
        &self.path
    }

    /// The entry stored under `key`.
    #[must_use]
    pub fn get(&self, key: &str) -> Option<EntryView<'_>> {
        self.document
            .entries
            .get_key_value(key)
            .map(|(key, entry)| view(key, entry))
    }

    /// Latest committed revision, including deletions. An empty new vault is revision zero.
    #[must_use]
    pub fn revision(&self) -> u64 {
        self.document.next_revision.saturating_sub(1)
    }

    /// Every entry, ordered by key.
    pub fn entries(&self) -> impl Iterator<Item = EntryView<'_>> {
        self.document
            .entries
            .iter()
            .map(|(key, entry)| view(key, entry))
    }

    /// Stores `value` (a JSON object) under `key` and returns the entry's new revision.
    ///
    /// # Errors
    ///
    /// [`Error::InvalidKey`], [`Error::InvalidValue`], or the failure of writing the file; the
    /// vault in memory and on disk is unchanged then.
    pub fn set(&mut self, key: &str, value: &Value) -> Result<u64> {
        validate_key(key)?;
        if !value.is_object() {
            return Err(Error::InvalidValue {
                key: key.to_owned(),
                reason: "a credential value must be a JSON object",
            });
        }
        let text = json_text(value);
        if text.len() > MAX_VALUE_BYTES {
            return Err(Error::InvalidValue {
                key: key.to_owned(),
                reason: "the value exceeds 64 KiB",
            });
        }
        let revision = self.document.next_revision;
        let entry = StoredEntry {
            revision,
            updated_at: now_ms(),
            value: text,
        };
        let previous = self.document.entries.insert(key.to_owned(), entry);
        self.document.next_revision += 1;
        if let Err(error) = self.persist() {
            self.document.next_revision -= 1;
            match previous {
                Some(previous) => self.document.entries.insert(key.to_owned(), previous),
                None => self.document.entries.remove(key),
            };
            return Err(error);
        }
        Ok(revision)
    }

    /// Removes `key`; returns the revision of the removal, or `None` when there was no entry.
    ///
    /// # Errors
    ///
    /// [`Error::InvalidKey`], or the failure of writing the file; nothing changes then.
    pub fn delete(&mut self, key: &str) -> Result<Option<u64>> {
        validate_key(key)?;
        let Some(previous) = self.document.entries.remove(key) else {
            return Ok(None);
        };
        let revision = self.document.next_revision;
        self.document.next_revision += 1;
        if let Err(error) = self.persist() {
            self.document.next_revision -= 1;
            self.document.entries.insert(key.to_owned(), previous);
            return Err(error);
        }
        Ok(Some(revision))
    }

    fn persist(&self) -> Result<()> {
        let plaintext = self.document.to_bytes();
        let file = format::seal(&self.key, &plaintext)?;
        atomic::replace_with(self.steps.as_ref(), &self.path, &file)
    }
}

fn view<'a>(key: &'a str, entry: &'a StoredEntry) -> EntryView<'a> {
    EntryView {
        key,
        revision: entry.revision,
        updated_at: entry.updated_at,
        value: entry.value.as_str(),
    }
}

/// Checks a credential key: a known prefix followed by a non-empty name without control
/// characters, at most [`MAX_KEY_BYTES`] in total.
///
/// # Errors
///
/// [`Error::InvalidKey`] naming the rule that failed.
pub fn validate_key(key: &str) -> Result<()> {
    let invalid = |reason| {
        Err(Error::InvalidKey {
            key: key.chars().take(80).collect(),
            reason,
        })
    };
    let Some(prefix) = KEY_PREFIXES.iter().find(|p| key.starts_with(*p)) else {
        return invalid("it must start with provider/, oauth/ or mcp/");
    };
    if key.len() == prefix.len() {
        return invalid("the name after the prefix is empty");
    }
    if key.len() > MAX_KEY_BYTES {
        return invalid("it is longer than 256 bytes");
    }
    if key.chars().any(char::is_control) {
        return invalid("it contains control characters");
    }
    Ok(())
}

fn now_ms() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_or(0, |d| u64::try_from(d.as_millis()).unwrap_or(u64::MAX))
}

#[cfg(test)]
mod tests {
    //! T08-A05: a write that fails part-way leaves the previous vault intact and readable.

    use std::fs::File;
    use std::io::{self, Write};
    use std::path::Path;

    use serde_json::json;

    use super::*;
    use crate::MemorySecretStore;
    use crate::master_key::master_key_name;

    #[derive(Clone, Copy, Debug)]
    enum FailAt {
        /// Half the bytes reach the temporary file, then the write fails.
        PartialWrite,
        Sync,
        Rename,
    }

    struct Failing(FailAt);

    impl WriteSteps for Failing {
        fn write(&self, file: &mut File, bytes: &[u8]) -> io::Result<()> {
            if let FailAt::PartialWrite = self.0 {
                file.write_all(&bytes[..bytes.len() / 2])?;
                return Err(io::Error::other("injected failure after a partial write"));
            }
            file.write_all(bytes)
        }

        fn sync(&self, file: &File) -> io::Result<()> {
            if let FailAt::Sync = self.0 {
                return Err(io::Error::other("injected sync failure"));
            }
            file.sync_all()
        }

        fn rename(&self, from: &Path, to: &Path) -> io::Result<()> {
            if let FailAt::Rename = self.0 {
                return Err(io::Error::other("injected rename failure"));
            }
            std::fs::rename(from, to)
        }
    }

    fn files(dir: &Path) -> Vec<String> {
        let mut names: Vec<String> = std::fs::read_dir(dir)
            .expect("dir")
            .flatten()
            .map(|e| e.file_name().to_string_lossy().into_owned())
            .collect();
        names.sort();
        names
    }

    #[test]
    fn a_failed_write_keeps_the_previous_vault() {
        for fail_at in [FailAt::PartialWrite, FailAt::Sync, FailAt::Rename] {
            let dir = std::env::temp_dir().join(format!(
                "piarc vault atomic {fail_at:?} {}",
                std::process::id()
            ));
            let _ = std::fs::remove_dir_all(&dir);
            std::fs::create_dir_all(&dir).expect("dir");
            let config = VaultConfig {
                path: dir.join("secrets.vault"),
                master_key: master_key_name("piarc-test.atomic"),
            };
            let store = MemorySecretStore::new();
            let (mut vault, _) = Vault::open(&config, &store).expect("created");
            let old = json!({ "type": "api_key", "key": "old" });
            vault.set("provider/example", &old).expect("first write");
            let before = std::fs::read(&config.path).expect("file");
            drop(vault);

            let (mut vault, _) =
                Vault::open_with(&config, &store, Arc::new(Failing(fail_at))).expect("opened");
            let error = vault
                .set(
                    "provider/example",
                    &json!({ "type": "api_key", "key": "new" }),
                )
                .expect_err("injected failure");
            assert!(matches!(error, Error::Io { .. }), "{fail_at:?}: {error:?}");
            assert!(
                vault.delete("provider/example").is_err(),
                "{fail_at:?}: deletes fail the same way"
            );
            // Memory and disk still hold the old entry; no temporary file is left behind.
            let current: Value =
                serde_json::from_str(vault.get("provider/example").expect("entry").value)
                    .expect("json");
            assert_eq!(current, old, "{fail_at:?}");
            assert_eq!(std::fs::read(&config.path).expect("file"), before);
            assert_eq!(files(&dir), vec!["secrets.vault".to_owned()], "{fail_at:?}");
            drop(vault);

            let (vault, _) = Vault::open(&config, &store).expect("old vault readable");
            let reread: Value =
                serde_json::from_str(vault.get("provider/example").expect("entry").value)
                    .expect("json");
            assert_eq!(reread, old);
            let _ = std::fs::remove_dir_all(&dir);
        }
    }

    #[test]
    fn leftovers_of_a_crashed_write_are_removed_on_open() {
        let dir =
            std::env::temp_dir().join(format!("piarc vault leftovers {}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).expect("dir");
        let config = VaultConfig {
            path: dir.join("secrets.vault"),
            master_key: master_key_name("piarc-test.leftovers"),
        };
        let store = MemorySecretStore::new();
        let (mut vault, _) = Vault::open(&config, &store).expect("created");
        vault
            .set("provider/example", &json!({ "type": "api_key" }))
            .expect("set");
        drop(vault);
        // A process that died between creating and renaming its temporary file.
        std::fs::write(dir.join("secrets.vault.tmp-0123456789abcdef"), b"partial").expect("write");
        let (vault, _) = Vault::open(&config, &store).expect("opened");
        assert!(vault.get("provider/example").is_some());
        assert_eq!(files(&dir), vec!["secrets.vault".to_owned()]);
        let _ = std::fs::remove_dir_all(&dir);
    }
}
