//! piarc-ghostty-sys: libghostty-vt -sys layer: committed bindgen bindings, download and verification of official prebuilt artefacts (ADR-0017).
//!
//! # Responsibilities
//!
//! - The `-sys` layer for libghostty-vt: bindgen bindings committed to the repository, and download
//!   plus verification of the official prebuilt artefacts (ADR-0017).
//! - One of the two places where `unsafe` is allowed (the other is the NAPI boundary).
//!
//! # Not responsible for
//!
//! - Safe wrappers and terminal session logic (`piarc-term`).
//!
//! # Allowed workspace dependencies
//!
//! None. Only `piarc-term` may depend on this crate.
//!
//! The authoritative rules are in `crates/deps-rules.json`, enforced by
//! `scripts/ci/check-crate-deps.mjs` (architecture section 7.1).
//!
//! # Bindings
//!
//! [`bindings`] is generated by `node scripts/dev/gen-ghostty-bindings.mjs` with the pinned
//! bindgen-cli from `.tools/` and committed; do not edit it. It covers every `ghostty_*`
//! function and `Ghostty*` type of `ghostty/vt.h` for the version in `ghostty-vt.lock.json`.
//! The headers are compiled as C23 so every `GHOSTTY_ENUM_TYPED` enum is `int` on all targets
//! (MSVC and clang would otherwise disagree on the sign of the underlying type).
//!
//! Macros that bindgen cannot evaluate (casts such as `GHOSTTY_STYLE_FLAG_BOLD`,
//! `GHOSTTY_INIT_SIZED`) are not in the bindings; the safe wrapper in `piarc-term` defines what
//! it needs.
//!
//! # Prebuilt artefacts and linking
//!
//! `build.rs` downloads (or takes from the cache) the archive locked for the target, checks its
//! SHA-256 and minisign signature, unpacks it into `OUT_DIR` and links it: the static library
//! of the XCFramework on macOS, the import library of `ghostty-vt.dll` on Windows MSVC. The DLL
//! must sit next to the binary that loads it; `cargo:dll` (`DEP_GHOSTTY_VT_DLL`) names it.

