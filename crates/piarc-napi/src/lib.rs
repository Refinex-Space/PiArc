//! piarc-napi: thin NAPI-RS export layer producing the per-platform .node modules (ADR-0014).
//!
//! # Responsibilities
//!
//! - Thin NAPI-RS export layer over `piarc-core`; produces the per-platform `.node` modules loaded
//!   by the Electron main process (ADR-0014).
//! - Catches panics at the boundary and maps errors to structured objects with `kind` and
//!   `retryable`.
//! - One of the two places where `unsafe` is allowed (the other is `piarc-ghostty-sys`).
//!
//! # Not responsible for
//!
//! - Business logic of any kind: it only converts and forwards.
//! - Being loaded by renderer processes: only the main process loads Core.
//!
//! # Allowed workspace dependencies
//!
//! `piarc-core`, plus the foundation crates `piarc-protocol` and `piarc-ports` for the types it
//! converts.
//!
//! The authoritative rules are in `crates/deps-rules.json`, enforced by
//! `scripts/ci/check-crate-deps.mjs` (architecture section 7.1).
//!
//! # Exports (T04)
//!
//! - `CoreRuntime.create(options, onEvents)`, `shutdown()`, `state`: see [`runtime`]. The
//!   `onEvents` listener is a `ThreadsafeFunction` ([`sink`]); the ordered shutdown releases
//!   it.
//! - Terminals (T10, ADR-0017): `createTerminal`, `terminalInput`, `terminalKey`,
//!   `terminalResize`, `terminalFrame` (a Promise of the frame bytes) and `closeTerminal`
//!   ([`terminal`]).
//! - State (T13): `CoreRuntime.create` takes `dataDir` and `cacheDir`;
//!   `rebuildSessionIndex`, `projectTrust`, `decideProjectTrust`, `revokeProjectTrust` resolve
//!   with JSON
//!   ([`state`]).
//! - Sessions (T14): `CoreRuntime.create` takes `agentHost` (how Agent Hosts start) and
//!   `idleTimeoutMs`; `openWorkspace`, `closeWorkspace`, `createSession`, `resumeSession`,
//!   `forkSession`, `closeSession`, `prompt`, `steer`, `followUp`, `abort`, `editQueueItem`,
//!   `deleteQueueItem`, `reorderQueue`, `markSessionRead`, `transcriptWindow` resolve with JSON;
//!   `resendSnapshots` queues the list snapshots again ([`sessions`]).
//! - With the `testing` feature only: demo event sources, `echo`, `eventStats`, two panic
//!   triggers, terminal measurements and `agentHostProbe` (T12: one mock conversation with
//!   the packaged app's Agent Host) ([`testing`]).
//!
//! Every export runs its body through [`boundary::call`]: Core errors and panics become a
//! thrown `Error` with `code` and `data: { kind, retryable, details? }` (the
//! `piarc_protocol::ErrorObject` shape). `#[napi(catch_unwind)]` additionally covers the
//! argument conversion generated by NAPI-RS.
//!
//! Promises are settled through `JsDeferred` from Core's own runtime; `#[napi] async fn` is
//! not used because it would start NAPI-RS's separate global tokio runtime.

